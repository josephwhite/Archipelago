def get_level_entry(level_key: str) -> dict:
    return Y2ROLL_LEVEL_BY_KEY[level_key]


def get_y2roll_level_entry(world_number: int, level_number: int) -> dict:
    """
    Get Y2ROLL level info of a given world-level id.
    :param world_number:
    :param level_number: Level number in world
    :return: Level info
    """
    return Y2ROLL_WORLD_LEVEL_INFO[world_number]["levels"][level_number]


def get_y2roll_level_name(level_key: str) -> str:
    return get_level_entry(level_key)["name"]


def get_y2roll_level_display_name(world_number: int, level_number: int) -> str:
    level_entry = get_y2roll_level_entry(world_number, level_number)
    return f"{world_number}-{level_number}: {level_entry["name"]}"

def get_level_gem_count(level_key: str) -> int:
    return get_level_entry(level_key)["gems"]

